// Measures what every session loads before the task starts, per profile, and fails
// above the budgets in docs/portable-toolkit-design.md. Tokens are estimated as bytes/4,
// the same estimate `agtk check` (internal/check) uses. Each tool loads only its own
// instruction file: CLAUDE.md carries the model routing table when the profile routes
// models in the legacy preset format. The generated-file
// comment and the table come from the same text as the Go side (checks/routing.mjs).
import { readFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { resolve, section } from "./routing.mjs";
import { GEMINI_HANDOFF } from "./handoff.mjs";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const BUDGET = { instructions: 1200, skillCount: 15, skillTokens: 1500, agentTokens: 400 };
const tok = (s) => Math.round(Buffer.byteLength(s) / 4);
const read = (...p) => readFileSync(join(repo, ...p), "utf8");
const GENERATED = "<!-- Generated by agtk. Edit the profile's instructions and re-run `agtk apply`; changes made here are overwritten. -->";

function frontmatter(md) {
  const m = md.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return {};
  const out = {};
  let key = null;
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([\w-]+):\s*(.*)$/);
    if (kv) { key = kv[1]; out[key] = kv[2].replace(/^>-?\s*$/, ""); }
    else if (key && /^\s+/.test(line)) out[key] = `${out[key]} ${line.trim()}`.trim();
  }
  return out;
}

// The scalar and [a, b] values under `answers:` in profile.yaml; enough for tools, plans and routing.
function answers(profile) {
  const file = join(repo, "profiles", profile, "profile.yaml");
  const out = {};
  if (!existsSync(file)) return out;
  let inside = false;
  for (const line of readFileSync(file, "utf8").split(/\r?\n/)) {
    if (/^answers:\s*(#.*)?$/.test(line)) { inside = true; continue; }
    if (!inside) continue;
    if (/^\S/.test(line)) break;
    const kv = line.match(/^\s+([\w-]+):\s*(.*?)\s*(\s#.*)?$/);
    if (!kv) continue;
    const v = kv[2];
    out[kv[1]] = v.startsWith("[") ? v.slice(1, -1).split(",").map((x) => x.trim()).filter(Boolean) : v.replace(/^["']|["']$/g, "");
  }
  return out;
}

// The names under `items:` in profile.yaml.
function items(profile) {
  const out = [];
  let inside = false;
  for (const line of readFileSync(join(repo, "profiles", profile, "profile.yaml"), "utf8").split(/\r?\n/)) {
    if (/^items:\s*(#.*)?$/.test(line)) { inside = true; continue; }
    if (!inside) continue;
    const item = line.match(/^\s+-\s+([\w-]+)\s*(#.*)?$/);
    if (item) out.push(item[1]);
    else if (/^\S/.test(line)) break;
  }
  return out;
}

// Authored skills are in the catalog only (no pin, so not in baseline.json): their listed
// descriptions count when the profile chooses them.
function authoredSkills(profile) {
  const chosen = items(profile);
  return readdirSync(join(repo, "catalog")).filter((f) => f.endsWith(".yaml"))
    .map((f) => read("catalog", f))
    .filter((text) => /^kind:\s*skill\s*$/m.test(text) && /^authored:\s*true\s*$/m.test(text) && !/^explicit_only:\s*true\s*$/m.test(text))
    .map((text) => ({ name: text.match(/^id:\s*(\S+)/m)[1], dir: text.match(/^vendored:\s*(\S+)/m)[1] }))
    .filter((s) => chosen.includes(s.name));
}

// The instruction files agtk apply writes, as install.SetupInstructionTexts builds them.
function instructionTexts(profile, preset, plans) {
  const parts = [read("base", "AGENTS.md"), read("profiles", profile, "AGENTS.md")]
    .map((p) => p.replace(/^﻿/, "").replace(/[\r\n \t]+$/, ""));
  const codex = `${GENERATED}\n\n${parts.join("\n\n")}\n`;
  const claude = preset ? `${codex.replace(/[\r\n \t]+$/, "")}\n\n${section(preset, plans)}\n` : codex;
  return { claude, codex, gemini: `${codex}\n${GEMINI_HANDOFF}` };
}

const baseline = JSON.parse(read("skills", "baseline.json"));
let failed = false;
for (const profile of readdirSync(join(repo, "profiles"))) {
  const prof = JSON.parse(read("profiles", profile, "profile.json"));
  const ans = answers(profile);
  if ("models" in ans) {
    failed = true;
    console.log(`FAIL profile ${profile}: use agtk check for confirmed model routing`);
    continue;
  }
  const useClaude = !ans.tools || ans.tools.includes("claude_code");
  const useCodex = !ans.tools || ans.tools.includes("codex");
  const useGemini = !!ans.tools && ans.tools.includes("gemini");
  let preset = "";
  try { preset = resolve(ans.routing, ans.plans, useClaude); }
  catch (e) { failed = true; console.log(`FAIL profile ${profile}: ${e.message}`); }
  const texts = instructionTexts(profile, preset, ans.plans);
  const listed = baseline.skills.filter((s) => prof.packs.includes(s.pack) && !s.explicit_only);
  const authored = authoredSkills(profile);
  const skillTokens = [
    ...listed.map((s) => ({ name: s.name, md: read("packs", s.pack, "skills", s.name, "SKILL.md") })),
    ...authored.map((s) => ({ name: s.name, md: read(s.dir, "SKILL.md") })),
  ].reduce((n, s) => n + tok(`${s.name}: ${frontmatter(s.md).description || ""}`), 0);
  let agentTokens = 0;
  for (const pack of prof.packs) {
    const dir = join(repo, "packs", pack, "agents");
    if (!existsSync(dir)) continue;
    for (const f of readdirSync(dir).filter((f) => f.endsWith(".md"))) {
      const fm = frontmatter(readFileSync(join(dir, f), "utf8"));
      agentTokens += tok(`${fm.name}: ${fm.description || ""}`);
    }
  }
  const rows = [];
  let instructions = 0;
  if (useClaude) {
    instructions = tok(texts.claude);
    rows.push(["instructions (CLAUDE.md)", instructions, BUDGET.instructions]);
  }
  if (useCodex) {
    const n = tok(texts.codex);
    rows.push(["instructions (AGENTS.md)", n, BUDGET.instructions]);
    instructions = Math.max(instructions, n); // a session loads one of the files
  }
  if (useGemini) {
    const n = tok(texts.gemini);
    rows.push(["instructions (GEMINI.md)", n, BUDGET.instructions]);
    instructions = Math.max(instructions, n);
  }
  rows.push(
    ["listed skills (count)", listed.length + authored.length, BUDGET.skillCount],
    ["listed skill descriptions", skillTokens, BUDGET.skillTokens],
    ["subagent descriptions", agentTokens, BUDGET.agentTokens],
  );
  console.log(`\n${profile}`);
  for (const [name, value, max] of rows) {
    const ok = value <= max;
    if (!ok) failed = true;
    console.log(`  ${ok ? "ok  " : "OVER"} ${name.padEnd(28)} ${String(value).padStart(5)} / ${max}`);
  }
  console.log(`  total always-loaded ~${instructions + skillTokens + agentTokens} tokens`);
}
process.exit(failed ? 1 : 0);
